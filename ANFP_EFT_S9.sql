PROMPT === CREACION DE TABLAS ===
CREATE TABLE REGION (
    ID_REGION NUMBER(2) CONSTRAINT PK_REGION PRIMARY KEY,
    NOMBRE VARCHAR2(70) NOT NULL,
    CONSTRAINT UQ_REGION_NOMBRE UNIQUE (NOMBRE)
);

CREATE TABLE COMUNA (
    ID_COMUNA NUMBER(5) CONSTRAINT PK_COMUNA PRIMARY KEY,
    ID_REGION NUMBER(2) NOT NULL,
    NOMBRE VARCHAR2(70) NOT NULL,
    CONSTRAINT FK_COMUNA_REGION FOREIGN KEY (ID_REGION) REFERENCES REGION (ID_REGION),
    CONSTRAINT UQ_COMUNA_REGION_NOM UNIQUE (ID_REGION, NOMBRE)
);

CREATE TABLE ASOCIACION (
    ID_ASOCIACION NUMBER(4) CONSTRAINT PK_ASOCIACION PRIMARY KEY,
    NOMBRE_ASOCIACION VARCHAR2(100) NOT NULL,
    FECHA_CREACION DATE NOT NULL,
    TIPO_ASOCIACION CHAR(1) NOT NULL,
    CONSTRAINT CK_ASOC_FECHA CHECK (FECHA_CREACION >= DATE '1980-12-31'),
    CONSTRAINT CK_ASOC_TIPO CHECK (TIPO_ASOCIACION IN ('P', 'A'))
);

CREATE TABLE NACIONALIDAD (
    ID_NACION NUMBER(3) GENERATED ALWAYS AS IDENTITY (START WITH 210 INCREMENT BY 2 NOCACHE)
        CONSTRAINT PK_NACIONALIDAD PRIMARY KEY,
    DESCRIPCION VARCHAR2(40) NOT NULL,
    CONSTRAINT UQ_NACION_DESC UNIQUE (DESCRIPCION)
);

CREATE TABLE CLUB_FUTBOL (
    ID_CLUB NUMBER(6) DEFAULT SEQ_CLUB_FUTBOL.NEXTVAL NOT NULL,
    NOMBRE_CLUB VARCHAR2(80) NOT NULL,
    PATRIMONIO NUMBER(15,2) NOT NULL,
    UBICACION_CALLE VARCHAR2(120) NOT NULL,
    TIPO_CLUB VARCHAR2(15) NOT NULL,
    CONSTRAINT PK_CLUB_FUTBOL PRIMARY KEY (ID_CLUB),
    CONSTRAINT UQ_CLUB_NOMBRE UNIQUE (NOMBRE_CLUB),
    CONSTRAINT CK_CLUB_PATRIM CHECK (PATRIMONIO >= 0),
    CONSTRAINT CK_CLUB_TIPO CHECK (TIPO_CLUB IN ('PROFESIONAL', 'AMATEUR'))
);

CREATE TABLE ESCUELA_FUTBOL (
    ID_ESCUELA NUMBER(6) CONSTRAINT PK_ESCUELA PRIMARY KEY,
    NOMBRE_ESCUELA VARCHAR2(100) NOT NULL,
    CAPACIDAD NUMBER(7) NOT NULL,
    FECHA_FUNDACION DATE NOT NULL,
    CONSTRAINT CK_ESCUELA_CAP CHECK (CAPACIDAD >= 0)
);

CREATE TABLE IDIOMA (
    ID_IDIOMA NUMBER(4) CONSTRAINT PK_IDIOMA PRIMARY KEY,
    NOMBRE_IDIOMA VARCHAR2(40) NOT NULL,
    CONSTRAINT UQ_IDIOMA_NOMBRE UNIQUE (NOMBRE_IDIOMA)
);

CREATE TABLE TRABAJADOR (
    ID_INSCRIPCION NUMBER(10) CONSTRAINT PK_TRABAJADOR PRIMARY KEY,
    RUT VARCHAR2(8) NOT NULL,
    DV CHAR(1) NOT NULL,
    NOMBRES VARCHAR2(60) NOT NULL,
    APELLIDOS VARCHAR2(80) NOT NULL,
    SUELDO_BASE NUMBER(12,2) NOT NULL,
    FECHA_NACIMIENTO DATE NOT NULL,
    GENERO CHAR(1) NOT NULL,
    ESTADO_CIVIL VARCHAR2(15) NOT NULL,
    TELEFONO_MOVIL VARCHAR2(15) NOT NULL,
    EMAIL VARCHAR2(100),
    DIRECCION VARCHAR2(150) NOT NULL,
    ID_COMUNA NUMBER(5) NOT NULL,
    ID_NACION NUMBER(3) NOT NULL,
    CONSTRAINT UQ_TRAB_RUT_DV UNIQUE (RUT, DV),
    CONSTRAINT CK_TRAB_RUT CHECK (REGEXP_LIKE(RUT, '^[0-9]{7,8}$')),
    CONSTRAINT CK_TRAB_DV CHECK (REGEXP_LIKE(DV, '^[0-9Kk]$')),
    CONSTRAINT CK_TRAB_SUELDO CHECK (SUELDO_BASE >= 0),
    CONSTRAINT CK_TRAB_GENERO CHECK (GENERO IN ('F', 'M', 'O')),
    CONSTRAINT FK_TRAB_COMUNA FOREIGN KEY (ID_COMUNA) REFERENCES COMUNA (ID_COMUNA),
    CONSTRAINT FK_TRAB_NACION FOREIGN KEY (ID_NACION) REFERENCES NACIONALIDAD (ID_NACION)
);

CREATE TABLE JUGADOR (
    ID_INSCRIPCION NUMBER(10) CONSTRAINT PK_JUGADOR PRIMARY KEY,
    PUESTO VARCHAR2(30) NOT NULL,
    PREMIOS_ACUMULADOS NUMBER(15,2) DEFAULT 0 NOT NULL,
    ID_ASOCIACION NUMBER(4) NOT NULL,
    ID_ESCUELA NUMBER(6),
    ANIO_FIN_AMATEURISMO NUMBER(4),
    CONSTRAINT FK_JUG_TRAB FOREIGN KEY (ID_INSCRIPCION) REFERENCES TRABAJADOR (ID_INSCRIPCION),
    CONSTRAINT FK_JUG_ASOC FOREIGN KEY (ID_ASOCIACION) REFERENCES ASOCIACION (ID_ASOCIACION),
    CONSTRAINT FK_JUG_ESCUELA FOREIGN KEY (ID_ESCUELA) REFERENCES ESCUELA_FUTBOL (ID_ESCUELA),
    CONSTRAINT CK_JUG_PREMIOS CHECK (PREMIOS_ACUMULADOS >= 0),
    CONSTRAINT CK_JUG_ESC_ANIO CHECK ((ID_ESCUELA IS NULL AND ANIO_FIN_AMATEURISMO IS NULL) OR (ID_ESCUELA IS NOT NULL AND ANIO_FIN_AMATEURISMO IS NOT NULL))
);

CREATE TABLE PERSONAL_PLANTA (
    ID_INSCRIPCION NUMBER(10) CONSTRAINT PK_PERSONAL_PLANTA PRIMARY KEY,
    HORAS_TRABAJADAS NUMBER(6,2),
    VALOR_HORAS_EXTRAS NUMBER(10,2),
    CONSTRAINT FK_PLANTA_TRAB FOREIGN KEY (ID_INSCRIPCION) REFERENCES TRABAJADOR (ID_INSCRIPCION),
    CONSTRAINT CK_PLANTA_HORAS CHECK (HORAS_TRABAJADAS IS NULL OR HORAS_TRABAJADAS >= 0),
    CONSTRAINT CK_PLANTA_VALOR CHECK (VALOR_HORAS_EXTRAS IS NULL OR VALOR_HORAS_EXTRAS >= 0),
    CONSTRAINT CK_PLANTA_PAR CHECK ((HORAS_TRABAJADAS IS NULL AND VALOR_HORAS_EXTRAS IS NULL) OR (HORAS_TRABAJADAS IS NOT NULL AND VALOR_HORAS_EXTRAS IS NOT NULL))
);

CREATE TABLE TRAYECTORIA_CLUB (
    ID_INSCRIPCION NUMBER(10) NOT NULL,
    ID_CLUB NUMBER(6) NOT NULL,
    FECHA_INCORPORACION DATE NOT NULL,
    FECHA_FIN_CONTRATO DATE,
    CONSTRAINT PK_TRAYECTORIA_CLUB PRIMARY KEY (ID_INSCRIPCION, ID_CLUB, FECHA_INCORPORACION),
    CONSTRAINT FK_TRAY_JUG FOREIGN KEY (ID_INSCRIPCION) REFERENCES JUGADOR (ID_INSCRIPCION),
    CONSTRAINT FK_TRAY_CLUB FOREIGN KEY (ID_CLUB) REFERENCES CLUB_FUTBOL (ID_CLUB),
    CONSTRAINT CK_TRAY_FECHAS CHECK (FECHA_FIN_CONTRATO IS NULL OR FECHA_FIN_CONTRATO >= FECHA_INCORPORACION)
);

-- Evita registrar dos contratos vigentes simultaneos para el mismo jugador.
CREATE UNIQUE INDEX UX_TRAY_CLUB_ACTUAL ON TRAYECTORIA_CLUB
    (CASE WHEN FECHA_FIN_CONTRATO IS NULL THEN ID_INSCRIPCION END);

CREATE TABLE JUGADOR_IDIOMA (
    ID_INSCRIPCION NUMBER(10) NOT NULL,
    ID_IDIOMA NUMBER(4) NOT NULL,
    NIVEL_DOMINIO VARCHAR2(15) NOT NULL,
    CONSTRAINT PK_JUGADOR_IDIOMA PRIMARY KEY (ID_INSCRIPCION, ID_IDIOMA),
    CONSTRAINT FK_JIDI_JUG FOREIGN KEY (ID_INSCRIPCION) REFERENCES JUGADOR (ID_INSCRIPCION),
    CONSTRAINT FK_JIDI_IDIOMA FOREIGN KEY (ID_IDIOMA) REFERENCES IDIOMA (ID_IDIOMA),
    CONSTRAINT CK_JIDI_NIVEL CHECK (NIVEL_DOMINIO IN ('BASICO', 'INTERMEDIO', 'AVANZADO', 'NATIVO'))
);

