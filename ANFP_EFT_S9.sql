PROMPT === CONSULTA 1: ASOCIACIONES PROFESIONALES POSTERIORES A 2000 ===
SELECT A.ID_ASOCIACION AS CODIGO,
       A.NOMBRE_ASOCIACION AS ASOCIACION,
       A.FECHA_CREACION AS FECHA_CREACION,
       A.TIPO_ASOCIACION AS TIPO
FROM ASOCIACION A
WHERE A.TIPO_ASOCIACION = 'P'
  AND A.FECHA_CREACION > DATE '2000-12-31'
ORDER BY A.FECHA_CREACION DESC;

PROMPT === CONSULTA 2: PATRIMONIO DE CLUBES EN PESOS Y DOLARES ===
SELECT C.ID_CLUB AS CLUB,
       C.NOMBRE_CLUB AS NOMBRE_CLUB,
       C.PATRIMONIO AS PATRIMONIO_EN_PESOS,
       ROUND(C.PATRIMONIO / 955, 2) AS PATRIMONIO_EN_DOLARES
FROM CLUB_FUTBOL C
WHERE LOWER(C.NOMBRE_CLUB) LIKE '%a%'
  AND C.PATRIMONIO > 200000000
  AND C.TIPO_CLUB = 'PROFESIONAL'
ORDER BY C.ID_CLUB DESC;

